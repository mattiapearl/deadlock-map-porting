def run(cmd: list[str], log: Path | None = None, timeout: int | None = None) -> subprocess.CompletedProcess:
    print("$", " ".join(map(str, cmd)), flush=True)
    if log:
        with log.open("w", encoding="utf-8", errors="replace") as f:
            p = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, text=True, timeout=timeout)
    else:
        p = subprocess.run(cmd, text=True, timeout=timeout)
    print("  rc=", p.returncode, flush=True)
    if p.returncode != 0:
        raise SystemExit(f"command failed rc={p.returncode}: {' '.join(map(str, cmd))}; see {log}")
    return p


def copytree_clean(src: Path, dst: Path):
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)


def _vmat_param(text: str, *names: str) -> str | None:
    for name in names:
        m = re.search(rf'"{re.escape(name)}"\s+"([^"]+)"', text)
        if m:
            return m.group(1)
    return None


def _vmat_flag(text: str, name: str) -> bool:
    return bool(re.search(rf'"{re.escape(name)}"\s+"?(?:1|true)"?', text, re.I))


def _write_sky_fallback(path: Path, text: str, reason: str) -> str:
    path.with_suffix(path.suffix + f".{reason}.bak").write_text(text, encoding="utf-8")
    path.write_text(
        f"// Rebound to CSDK sky texture for Deadlock compile compatibility ({reason})\n\n"
        '"Layer0"\n{\n\t"shader"\t"sky.vfx"\n'
        '\t"g_flBrightnessExposureBias"\t"-1"\n'
        '\t"g_flRenderOnlyExposureBias"\t"0"\n'
        '\t"SkyTexture"\t"materials/skybox/sky_dl_dusk03_exr_9dd50fb1.png"\n'
        "}\n",
        encoding="utf-8",
    )
    return "sky"


def _write_pbr(path: Path, text: str, shader: str, mode: str) -> str:
    color = _vmat_param(text, "TextureColor", "TextureLayer1Color", "g_tColor") or "materials/default/default_color.tga"
    normal = _vmat_param(text, "TextureNormal", "TextureLayer1NormalRoughness", "g_tNormal", "g_tLayer1NormalRoughness")
    self_mask = _vmat_param(text, "TextureSelfIllumMask", "g_tSelfIllumMask")
    tint = _vmat_param(text, "g_vColorTint", "g_vLayer1Tint") or "[1.000000 1.000000 1.000000 0.000000]"
    metal = _vmat_param(text, "g_flMetalness") or "0.000000"
    opacity = _vmat_param(text, "g_flOpacityScale") or "1.000000"
    self_scale = _vmat_param(text, "g_flSelfIllumScale", "g_flSelfIllumBrightness") or "1.000000"
    self_tint = _vmat_param(text, "g_vSelfIllumTint") or tint

    is_emissive = _vmat_flag(text, "F_SELF_ILLUM") or self_mask is not None or "SelfIllum" in text
    if is_emissive:
        try:
            # CS2 csgo_complex self-illum reads much hotter than Deadlock pbr at
            # scale 1.0. Boost conservatively so glowing bhop guide blocks remain
            # visibly emissive without turning the whole map into a bloom bomb.
            self_scale = f"{max(float(self_scale), 2.5):.6f}"
        except ValueError:
            self_scale = "2.500000"
    is_translucent = _vmat_flag(text, "F_TRANSLUCENT") or opacity not in ("1", "1.0", "1.00", "1.000000")
    is_glass = "glass" in shader.lower() or "glass" in path.stem.lower()

    path.with_suffix(path.suffix + f".{shader.replace('.vfx','')}.bak").write_text(text, encoding="utf-8")

    lines = [
        f"// Ported from CS2 {shader} to Deadlock pbr.vfx ({mode})",
        "// Generated by full_recompile_bhop_rose_from_mapping_recipe.py",
        "",
        '"Layer0"',
        "{",
        '\t"shader"\t"pbr.vfx"',
    ]
    if is_emissive:
        # Keep glowing CS2 materials bright/readable in Deadlock. This preserves the
        # visible emissive object; actual cast/baked light still comes from lights/VRAD.
        lines.append('\t"F_UNLIT"\t"1"')
        lines.append('\t"F_SELF_ILLUM"\t"1"')
    if is_glass:
        lines.append('\t"F_GLASS"\t"1"')
    if is_translucent and not is_glass:
        lines.append('\t"F_TRANSLUCENT"\t"1"')
    lines += [
        f'\t"TextureColor1"\t"{color}"',
        f'\t"g_vColorTint1"\t"{tint}"',
        f'\t"g_flOpacityScale1"\t"{opacity}"',
    ]
    if normal:
        lines.append(f'\t"TextureNormal1"\t"{normal}"')
    else:
        lines.append('\t"TextureNormal1"\t"materials/default/default_normal.tga"')
    if is_emissive:
        lines += [
            '\t"g_flSelfIllumAlbedoFactor1"\t"1.000000"',
            f'\t"g_flSelfIllumScale1"\t"{self_scale}"',
            f'\t"g_vSelfIllumTint1"\t"{self_tint}"',
            f'\t"TextureSelfIllumMask1"\t"{self_mask or color}"',
        ]
    if is_glass:
        lines.append(f'\t"TextureGlassMask1"\t"{self_mask or color}"')
    lines += [
        '\t"TextureRoughness1"\t"[0.350000 0.350000 0.350000 0.000000]"',
        f'\t"TextureMetalness1"\t"[{metal} {metal} {metal} 0.000000]"',
        "}",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    if is_emissive:
        return "emissive_pbr"
    if is_glass:
        return "glass_pbr"
    if is_translucent:
        return "translucent_pbr"
    if normal or tint != "[1.000000 1.000000 1.000000 0.000000]" or metal not in ("0", "0.0", "0.000000"):
        return "enriched_pbr"
    return "pbr"


def rewrite_vmat(path: Path):
    text = path.read_text(errors="replace")
    shader = _vmat_param(text, "shader")
    if shader == "csgo_moondome.vfx":
        return _write_sky_fallback(path, text, "csgo_moondome")
    if shader == "sky.vfx":
        # Custom CS2 skies often decompile into split faces while the VMAT points at
        # a missing logical cubemap name. Rebind to a known compiling Deadlock sky.
        return _write_sky_fallback(path, text, "custom_sky")
    if shader and shader.startswith("csgo_"):
        if shader == "csgo_water_fancy.vfx":
            return _write_pbr(path, text, shader, "water_degraded")
        return _write_pbr(path, text, shader, "classified")
    return None


def make_texture_settings(materials_root: Path):
    for img in list(materials_root.rglob("*.png")) + list(materials_root.rglob("*.tga")) + list(materials_root.rglob("*.exr")):
        txt = img.with_suffix(".txt")
        if not txt.exists():
            txt.write_text('"settings"\n{\n}\n', encoding="utf-8")


def stage_and_rewrite_materials():
    print("[stage] cleaning addon dirs")
    if CONTENT_ADDON.exists(): shutil.rmtree(CONTENT_ADDON)
    if GAME_ADDON.exists(): shutil.rmtree(GAME_ADDON)
    (CONTENT_ADDON / "maps").mkdir(parents=True)
    GAME_ADDON.mkdir(parents=True)
    (GAME_ADDON / "addoninfo.txt").write_text('"addoninfo"\n{\n\t"IsPlayable"\t"1"\n}\n', encoding="utf-8")

    print("[stage] copy decompiled maps to content")
    shutil.copytree(DECOMP_INNER / "maps", CONTENT_ADDON / "maps", dirs_exist_ok=True)
    print("[stage] copy decompiled materials/postprocess/sounds to content")
    for sub in ["materials", "postprocess", "soundevents", "sounds"]:
        s = DECOMP_OUTER / sub
        if s.exists():
            shutil.copytree(s, CONTENT_ADDON / sub, dirs_exist_ok=True)
    mats = CONTENT_ADDON / "materials"
    # VRF may decompile cubemap sky faces as ssss_png_<hash>_ft.png etc while the VMAT
    # still refers to materials/skybox/ssss.png. Provide a concrete source image so
    # sky.vfx can compile instead of leaving the sky material unresolved.
    sky_missing = mats / "skybox" / "ssss.png"
    if not sky_missing.exists():
        faces = sorted((mats / "skybox").glob("ssss_png_*_ft.png")) + sorted((mats / "skybox").glob("ssss_png_*_up.png"))
        if faces:
            shutil.copy2(faces[0], sky_missing)
    make_texture_settings(mats)
    counts = collections.Counter()
    for vmat in mats.rglob("*.vmat"):
        kind = rewrite_vmat(vmat)
        if kind:
            counts[kind] += 1
    print("[materials] rewritten", dict(counts))


