def patch_vmap_entities():
    vmap = CONTENT_ADDON / "maps" / f"{MAP}.vmap"
    kv2 = WORK / f"{MAP}.kv2.txt"
    patched = WORK / f"{MAP}.patched.kv2.txt"
    convert_vmap_to_kv2(vmap, kv2)
    text = kv2.read_text(errors="replace")

    # VRF decompile emits prop_static aggregate worldnode proxies on top of the
    # reconstructed Hammer meshes. The mapping docs explicitly call these a
    # decompile artifact (z-fighting / duplicate aggregate props). Remove the
    # static aggregate proxy, not the actual reconstructed CMapMesh geometry.
    aggregate_model = f'"model" "string" "maps/{MAP}/worldnodes/n0_lr0_c2_s_cb_mesh.vmdl"'
    pos = text.find(aggregate_model)
    if pos >= 0:
        block_start = text.rfind('\n"CMapEntity"', 0, pos)
        if block_start >= 0:
            brace = text.find('{', block_start)
            depth = 1; j = brace + 1
            while j < len(text) and depth:
                if text[j] == '{': depth += 1
                elif text[j] == '}': depth -= 1
                j += 1
            block = text[block_start:j]
            m_id = re.search(r'"id" "elementid" "([^"]+)"', block)
            if m_id:
                eid = m_id.group(1)
                text = text[:block_start] + text[j:]
                text = re.sub(r'\n\s*"element" "' + re.escape(eid) + r'",?', '', text, count=1)
                print(f"[entities] removed aggregate prop_static proxy {eid}")

    origin = find_origin_near_start(text)
    nid = next_node_id(text)
    new_entities: list[tuple[str, str]] = []
    if '"classname" "string" "point_servercommand"' not in text:
        new_entities.append(make_entity("point_servercommand", {"targetname": "panel", "vscripts": ""}, "0 0 0", nid)); nid += 1
    if '"classname" "string" "logic_auto"' not in text:
        new_entities.append(make_entity("logic_auto", {"spawnflags": "0", "vscripts": "", "targetname": "", "globalstate": ""}, "0 0 0", nid, make_connection())); nid += 1
    for team in (2, 3, 4):
        # Always add explicit Deadlock team spawns; CS2 info_player_* is not enough.
        new_entities.append(make_entity("info_team_spawn", {"grouptag": "0", "initialspawn": "0", "teamnumber": str(team), "lanenum": "6", "vscripts": "", "targetname": "", "hero_model": ""}, origin, nid)); nid += 1
    if '"targetname" "string" "stage1"' not in text:
        new_entities.append(make_entity("info_teleport_destination", {"targetname": "stage1"}, origin, nid)); nid += 1

    refs = [eid for eid, _ in new_entities]
    blocks = [block for _, block in new_entities]

    # Add element refs to CMapWorld.children (the first children array in the file).
    children_key = '"children" "element_array"'
    ck = text.find(children_key)
    arr_open = text.find('[', ck)
    arr_close = text.find('\n\t\t]', arr_open)
    if ck < 0 or arr_open < 0 or arr_close < 0:
        raise SystemExit("could not find CMapWorld children array")
    before_close = text[:arr_close].rstrip()
    sep = ",\n" if not before_close.endswith('[') else "\n"
    ref_text = sep + ",\n".join(f'\t\t\t"element" "{eid}"' for eid in refs)
    text = text[:arr_close] + ref_text + text[arr_close:]

    # Append top-level CMapEntity blocks. The element refs above point to their ids.
    new_text = text.rstrip() + "\n" + "\n".join(blocks) + "\n"
    patched.write_text(new_text, encoding="utf-8", errors="replace")
    print(f"[entities] inserted {len(blocks)} blocks / refs at origin {origin}")
    convert_kv2_to_vmap(patched, vmap)


def compile_materials():
    vmats = sorted((CONTENT_ADDON / "materials").rglob("*.vmat"))
    print(f"[compile] {len(vmats)} vmats")
    ok = 0
    for v in vmats:
        rel = v.relative_to(CONTENT_ADDON)
        log = LOG_DIR / f"compile_{ADDON}_{str(rel).replace(os.sep, '_')}.log"
        run([str(RC), "-i", str(v), "-game", str(GAME), "-nop4"], log=log, timeout=300)
        ok += 1
    print(f"[compile] material OK {ok}")


def compile_postprocess():
    vposts = sorted((CONTENT_ADDON / "postprocess").rglob("*.vpost")) if (CONTENT_ADDON / "postprocess").exists() else []
    print(f"[compile] {len(vposts)} vposts")
    for v in vposts:
        rel = v.relative_to(CONTENT_ADDON)
        log = LOG_DIR / f"compile_{ADDON}_{str(rel).replace(os.sep, '_')}.log"
        run([str(RC), "-i", str(v), "-game", str(GAME), "-nop4"], log=log, timeout=300)


def compile_models():
    vmdls = sorted((CONTENT_ADDON / "maps" / MAP).rglob("*.vmdl")) if (CONTENT_ADDON / "maps" / MAP).exists() else []
    print(f"[compile] {len(vmdls)} vmdls")
    for v in vmdls:
        rel = v.relative_to(CONTENT_ADDON)
        log = LOG_DIR / f"compile_{ADDON}_{str(rel).replace(os.sep, '_')}.log"
        run([str(RC), "-i", str(v), "-game", str(GAME), "-nop4"], log=log, timeout=300)


def compile_map():
    log = LOG_DIR / f"compile_{ADDON}_{int(time.time())}.log"
    run([sys.executable, str(ROOT / "tools/compile_with_memory_limit.py"), "--limit-gb", "28", "--", str(RC), "-i", str(CONTENT_ADDON / "maps" / f"{MAP}.vmap"), "-game", str(GAME), "-nop4"], log=log, timeout=7200)
    print(f"[compile] map log {log}")


def main():
    stage_and_rewrite_materials()
    patch_vmap_entities()
    compile_materials()
    compile_postprocess()
    compile_models()
    compile_map()
    print("DONE")
    print("game addon:", GAME_ADDON)

if __name__ == "__main__":
    main()
