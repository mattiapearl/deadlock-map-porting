def convert_kv2_to_vmap(src: Path, dst: Path):
    run([str(DMX), "-i", str(src), "-o", str(dst), "-oe", "binary", "-of", "vmap"], log=WORK / "dmx_to_binary.log", timeout=600)


def find_origin_near_start(text: str) -> str:
    # Prefer the existing named start teleport destination if present.
    idx = text.find('"targetname" "string" "Start"')
    if idx < 0:
        idx = text.find('"classname" "string" "info_teleport_destination"')
    if idx >= 0:
        block_start = text.rfind('"CMapEntity"', 0, idx)
        block_end = text.find('\n\t\t\t"CMapEntity"', idx)
        block = text[block_start:block_end if block_end > 0 else idx + 5000]
        m = re.search(r'"origin" "vector3" "([^"]+)"', block)
        if m:
            return m.group(1)
    return "0 0 128"


def next_node_id(text: str) -> int:
    nums = [int(x) for x in re.findall(r'"nodeID" "int" "(\d+)"', text)]
    return (max(nums) + 1000) if nums else 99000


